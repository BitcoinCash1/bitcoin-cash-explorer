CREATE DATABASE benchmark;
USE benchmark;
CREATE TABLE blocks (hash VARCHAR(65) PRIMARY KEY, height INT UNSIGNED NOT NULL, stale BOOL NOT NULL DEFAULT 0, pool_id SMALLINT UNSIGNED, blockTimestamp TIMESTAMP NOT NULL, reward BIGINT UNSIGNED NOT NULL, payload VARCHAR(600), INDEX(height), INDEX(stale), INDEX(pool_id)) ENGINE=InnoDB;
INSERT INTO blocks SELECT LPAD(seq,64,'0'), seq, IF(seq%20000=0,1,0), IF(seq%2=0,1,2), FROM_UNIXTIME(1200000000+seq*500), 5000000000, REPEAT('x',600) FROM seq_1_to_1000000;
CREATE TABLE blocks_summaries (id VARCHAR(65) PRIMARY KEY, height INT UNSIGNED NOT NULL, version INT NOT NULL, transactions JSON, INDEX(height), INDEX(version));
INSERT INTO blocks_summaries SELECT hash,height,1,'[]' FROM blocks;
